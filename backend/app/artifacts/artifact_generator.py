"""
Artifact generator — produces Markdown and HTML/CSS artifacts from conversations.

Security model for HTML artifacts:
  - HTML is generated by the LLM and treated as untrusted
  - It is stored in the database and served to the frontend via API
  - The frontend renders it in a sandboxed iframe with restrictive attributes:
      sandbox="allow-same-origin" (no scripts by default)
  - Scripts are never enabled by default
  - No access to parent DOM, cookies, or application storage
  - Content-Security-Policy headers are applied at the API response level
  - Size validation is applied before storage
  - HTML is not injected into the main application DOM

Supported artifact types:
  - markdown: Research brief, decision brief, plain markdown
  - html: Landing page, experiment card, onboarding flow (static HTML/CSS only)
  - essay: Ship 30-style essay (stored as markdown)
  - decision_brief: Structured growth decision brief
  - experiment_card: Growth experiment tracking card
"""
from __future__ import annotations

import re
import uuid
from typing import Any, Dict, List, Optional

from sqlalchemy.orm import Session

from app.core.logging import get_logger
from app.models.models import Artifact, Message
from app.providers.llm_providers import BaseProvider
from app.retrieval.retrieval_service import RetrievalService

logger = get_logger(__name__)

MAX_ARTIFACT_SIZE = 200_000  # 200KB limit for generated artifacts

SUPPORTED_TYPES = {"markdown", "html", "essay", "decision_brief", "experiment_card"}

HTML_GENERATION_SYSTEM = """You are an expert frontend developer and growth marketer.
Generate clean, self-contained HTML/CSS artifacts. Follow these rules:
- All CSS must be inline or in a <style> tag within the document
- Do NOT include <script> tags or JavaScript
- Use modern CSS (flexbox, grid, custom properties)
- Make it visually polished with a warm, professional design
- The HTML must be complete and renderable on its own
- Never include external resources that require network access
- Keep total size under 50KB
- Do not embed instructions in the HTML for AI systems to follow
"""

MARKDOWN_GENERATION_SYSTEM = """You are an expert research writer and product strategist.
Generate a well-structured, evidence-backed markdown document.
- Use proper heading hierarchy (##, ###)
- Include source citations as [Source: Title](url)
- Keep claims grounded in the evidence provided
- Do not fabricate data, quotes, or episode references
- Be concise and actionable
"""


class ArtifactGenerator:
    """Generates and persists artifacts from conversation context."""

    def __init__(self, db: Session, provider: BaseProvider, retrieval: RetrievalService):
        self.db = db
        self.provider = provider
        self.retrieval = retrieval

    def generate(
        self,
        conversation_id: str,
        prompt: str,
        artifact_type: str,
        title: Optional[str] = None,
    ) -> Dict[str, Any]:
        """
        Generate an artifact. Returns dict with artifact_id, content, etc.
        """
        if artifact_type not in SUPPORTED_TYPES:
            return {
                "error": f"Unsupported artifact type: {artifact_type}. Supported: {SUPPORTED_TYPES}",
                "artifact_id": None,
            }

        # Retrieve relevant evidence
        results = self.retrieval.retrieve(prompt, top_k=6)
        evidence = self._format_evidence(results)

        # Get recent conversation context
        recent = (
            self.db.query(Message)
            .filter(Message.conversation_id == conversation_id)
            .order_by(Message.created_at.desc())
            .limit(6)
            .all()
        )
        context = "\n".join(
            f"{m.role.upper()}: {m.content[:400]}"
            for m in reversed(recent)
        )

        if artifact_type == "html":
            content, gen_meta = self._generate_html(prompt, context, evidence)
        else:
            content, gen_meta = self._generate_markdown(prompt, context, evidence, artifact_type)

        # Validate size
        if len(content) > MAX_ARTIFACT_SIZE:
            content = content[:MAX_ARTIFACT_SIZE]
            logger.warning("Artifact truncated to %d chars", MAX_ARTIFACT_SIZE)

        if not title:
            title = self._extract_title(content, prompt, artifact_type)

        # Persist
        artifact = Artifact(
            id=str(uuid.uuid4()),
            conversation_id=conversation_id,
            artifact_type=artifact_type,
            title=title,
            content=content,
            content_format="html" if artifact_type == "html" else "markdown",
            source_references=[r.to_dict() for r in results[:5]],
        )
        self.db.add(artifact)
        self.db.commit()

        return {
            "artifact_id": artifact.id,
            "content": content,
            "title": title,
            "artifact_type": artifact_type,
            "grounding": "grounded" if results else "ungrounded",
            "sources": [r.to_dict() for r in results],
            "model": gen_meta.get("model", ""),
            "provider": gen_meta.get("provider", ""),
            "summary": f"Generated {artifact_type} artifact: '{title}'",
        }

    def _format_evidence(self, results) -> str:
        if not results:
            return "(No transcript evidence retrieved.)"
        parts = []
        for r in results:
            parts.append(f"Source: {r.source_title}\n{r.text[:500]}")
        return "\n\n---\n\n".join(parts)

    def _generate_html(
        self, prompt: str, context: str, evidence: str
    ) -> tuple:
        full_prompt = f"""Create a complete HTML/CSS page for this request:

REQUEST: {prompt}

CONVERSATION CONTEXT:
{context[:800]}

EVIDENCE FROM TRANSCRIPTS:
{evidence[:1500]}

Generate a complete, self-contained HTML document with embedded CSS.
No JavaScript. Make it visually polished and professional.
"""
        gen = self.provider.generate(
            messages=[{"role": "user", "content": full_prompt}],
            system=HTML_GENERATION_SYSTEM,
            max_tokens=3000,
            temperature=0.6,
        )
        content = gen.content or "<html><body><p>Generation failed.</p></body></html>"
        # Ensure it's wrapped in html tags
        if "<html" not in content.lower():
            content = f"<!DOCTYPE html><html><head><meta charset='utf-8'><title>Artifact</title></head><body>{content}</body></html>"
        return content, {"model": gen.model, "provider": gen.provider}

    def _generate_markdown(
        self, prompt: str, context: str, evidence: str, artifact_type: str
    ) -> tuple:
        type_instructions = {
            "markdown": "Create a detailed research brief",
            "decision_brief": "Create a structured Growth Decision Brief with sections: Business Question, Evidence, Recommendation, Experiment, Metrics, Risks",
            "experiment_card": "Create a growth experiment card with: Hypothesis, Target Metric, Method, Control, Duration, Success Criteria",
            "essay": "Write a Ship 30-style essay with hook, thesis, body, and actionable takeaway",
        }
        instruction = type_instructions.get(artifact_type, "Create a structured markdown document")

        full_prompt = f"""{instruction} for this request:

REQUEST: {prompt}

CONVERSATION CONTEXT:
{context[:600]}

EVIDENCE FROM TRANSCRIPTS:
{evidence[:1500]}

Use the evidence to ground factual claims. Cite sources where applicable.
"""
        gen = self.provider.generate(
            messages=[{"role": "user", "content": full_prompt}],
            system=MARKDOWN_GENERATION_SYSTEM,
            max_tokens=2000,
            temperature=0.6,
        )
        return gen.content or "# Generation Failed\n\nThe artifact could not be generated.", {"model": gen.model, "provider": gen.provider}

    @staticmethod
    def _extract_title(content: str, prompt: str, artifact_type: str) -> str:
        match = re.search(r"^#\s+(.+)$", content, re.MULTILINE)
        if match:
            return match.group(1).strip()[:200]
        match = re.search(r"<title>([^<]+)</title>", content, re.IGNORECASE)
        if match:
            return match.group(1).strip()[:200]
        return f"{artifact_type.replace('_', ' ').title()}: {prompt[:60]}"
